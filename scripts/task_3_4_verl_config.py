def main():
    # Cancel old GRPO job if still running
    print("Checking for old GRPO job 1855278...")
    try:
        result = subprocess.run(
            ["squeue", "-j", "1855278", "--noheader"],
            capture_output=True, text=True, timeout=10
        )
        if result.stdout.strip():
            print(f"  Job 1855278 still in queue: {result.stdout.strip()}")
            confirm = input("  Cancel it? [y/N] ").strip().lower()
            if confirm == "y":
                subprocess.run(["scancel", "1855278"], check=True)
                print("  Cancelled job 1855278.")
        else:
            print("  Job 1855278 not in queue (already done or expired).")
    except Exception as e:
        print(f"  Could not check/cancel job: {e}")

    # Query cluster
    print("\nQuerying cluster...")
    partitions = query_cluster()
    for p in partitions:
        print(f"  {p}")

    # Select config
    cfg = select_config(partitions)
    print(f"\nSelected config:")
    print(f"  partition={cfg['partition']}, gpus={cfg['n_gpus']}×{cfg['gpu_type']}")
    print(f"  model={cfg['model']}, lora={cfg['use_lora']}, group_size={cfg['group_size']}")

    # Write YAML
    yaml_path = ROOT / "configs/cps_anomaly_grpo.yaml"
    yaml_path.write_text(make_yaml_config(cfg))
    print(f"\nWrote {yaml_path}")

    # Write SLURM script
    slurm_path = ROOT / "slurm/submit_anomaly_grpo.sh"
    slurm_path.write_text(make_slurm_script(cfg))
    slurm_path.chmod(0o755)
    print(f"Wrote {slurm_path}")

    # Save summary
    (ROOT / "outputs/slurm").mkdir(exist_ok=True)
    summary = {
        "gpu_config":     cfg,
        "yaml_path":      str(yaml_path),
        "slurm_path":     str(slurm_path),
        "submit_command": f"sbatch {slurm_path}",
        "partitions_found": partitions,
    }
    (P3_OUT / "verl_config_summary.json").write_text(json.dumps(summary, indent=2))
    print("\nSaved verl_config_summary.json")
    print(f"\nTo submit: sbatch {slurm_path}")
    print("Done.")


if __name__ == "__main__":
    main()

from pathlib import Path

ROOT   = Path("/home/simran/allspark-data-exploration/CPS-Debugger")
P3_OUT = ROOT / "outputs/phase3"
P3_OUT.mkdir(parents=True, exist_ok=True)
(ROOT / "configs").mkdir(exist_ok=True)
(ROOT / "slurm").mkdir(exist_ok=True)


def query_cluster():
    """Query available partitions and GPU types."""
    try:
        result = subprocess.run(
            ["sinfo", "-p", "gpu,long,short", "--format=%P %G %m %a %D", "--noheader"],
            capture_output=True, text=True, timeout=10
        )
        lines = result.stdout.strip().split("\n")
        partitions = []
        for line in lines:
            parts = line.split()
            if len(parts) >= 5:
                partitions.append({
                    "partition": parts[0].rstrip("*"),
                    "gres":      parts[1],
                    "mem_mb":    parts[2],
                    "available": parts[3],
                    "n_nodes":   parts[4],
                })
        return partitions
    except Exception as e:
        print(f"  sinfo query failed: {e}")
        return []


def select_config(partitions):
    """Determine best GPU config based on cluster availability."""
    # Check for A100 80GB, A100 40GB, A6000, V100
    gpu_config = {
        "partition":   "long",
        "n_gpus":      4,
        "gpu_type":    "A100",
        "model":       "Qwen/Qwen2.5-Coder-7B-Instruct",
        "use_lora":    False,
        "lora_rank":   0,
        "group_size":  8,
        "batch_size":  32,
        "grad_accum":  2,
        "mem_gb":      128,
        "time":        "2-00:00:00",
    }

    for p in partitions:
        gres = p.get("gres", "").lower()
        if "a100" in gres or "gpu" in gres:
            gpu_config["partition"] = p["partition"]
            # Try to detect GPU memory from gres string
            if "80" in gres:
                gpu_config["use_lora"] = False  # full fine-tuning
            elif "40" in gres:
                gpu_config["use_lora"] = True
                gpu_config["lora_rank"] = 16
            break

    return gpu_config


